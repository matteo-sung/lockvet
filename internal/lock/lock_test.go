func TestGemfileLockNonRegistrySources(t *testing.T) {
	f := parseWith(t, "Gemfile.lock", `GIT
  remote: https://github.com/someone/fork.git
  revision: abc123
  specs:
    patched-gem (9.9.9)

PATH
  remote: engines/local
  specs:
    local-engine (0.1.0)

GEM
  remote: https://rubygems.org/
  specs:
    rack (3.0.0)

DEPENDENCIES
  local-engine!
  patched-gem!
  rack
`)
	wantPkg(t, f, "patched-gem", "9.9.9")
	wantPkg(t, f, "local-engine", "0.1.0")
	wantPkg(t, f, "rack", "3.0.0")
	if !f.NonRegistry["patched-gem"] {
		t.Error("GIT-sourced gems must be marked non-registry")
	}
	if !f.NonRegistry["local-engine"] {
		t.Error("PATH-sourced gems must be marked non-registry")
	}
	if f.NonRegistry["rack"] {
		t.Error("GEM-sourced gems must not be marked non-registry")
	}
}

func TestGoModReplaceNonRegistry(t *testing.T) {
	f := parseWith(t, "go.mod", `module example.com/app

require (
	github.com/grafana/grafana/pkg/apimachinery v0.0.0
	github.com/pkg/errors v0.9.1
)

require github.com/acme/single v1.2.3

replace github.com/acme/single => ../single

replace (
	github.com/grafana/grafana/pkg/apimachinery => ../../pkg/apimachinery
	github.com/other/mod v1.0.0 => github.com/fork/mod v1.0.1
)
`)
	for _, name := range []string{"github.com/grafana/grafana/pkg/apimachinery", "github.com/acme/single", "github.com/other/mod"} {
		if !f.NonRegistry[name] {
			t.Errorf("%s: replaced module not marked NonRegistry", name)
		}
	}
	if f.NonRegistry["github.com/pkg/errors"] {
		t.Error("github.com/pkg/errors wrongly marked NonRegistry")
	}
	if len(f.Packages["github.com/pkg/errors"]) == 0 || len(f.Packages["github.com/acme/single"]) == 0 {
		t.Error("require entries missing from Packages")
	}
}

func TestYarnNpmAliasNonRegistry(t *testing.T) {
	f := parseWith(t, "yarn.lock", `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8

"wrap-ansi-cjs@npm:wrap-ansi@^7.0.0":
  version: 7.0.0
  resolution: "wrap-ansi@npm:7.0.0"

"chalk@npm:^5.0.0":
  version: 5.3.0
  resolution: "chalk@npm:5.3.0"

"@scoped/alias@npm:@real/pkg@^1.0.0":
  version: 1.4.0
  resolution: "@real/pkg@npm:1.4.0"
`)
	if !f.NonRegistry["wrap-ansi-cjs"] {
		t.Error("wrap-ansi-cjs alias not marked NonRegistry")
	}
	if !f.NonRegistry["@scoped/alias"] {
		t.Error("@scoped/alias not marked NonRegistry")
	}
	if f.NonRegistry["chalk"] {
		t.Error("chalk (plain npm: range, no alias) wrongly marked NonRegistry")
	}
	if len(f.Packages["wrap-ansi-cjs"]) == 0 || len(f.Packages["chalk"]) == 0 {
		t.Error("yarn entries missing from Packages")
	}
}

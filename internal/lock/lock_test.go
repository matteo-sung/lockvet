package lock

import (
	"reflect"
	"testing"
)

func parseWith(t *testing.T, name string, data string) *File {
	t.Helper()
	p := ByBasename(name)
	if p == nil {
		t.Fatalf("no parser for %s", name)
	}
	f, err := p.Parse(name, []byte(data))
	if err != nil {
		t.Fatalf("parse %s: %v", name, err)
	}
	return f
}

func wantPkg(t *testing.T, f *File, name string, versions ...string) {
	t.Helper()
	if got := f.Packages[name]; !reflect.DeepEqual(got, versions) {
		t.Errorf("%s: package %q = %v, want %v", f.Kind, name, got, versions)
	}
}

func TestPackageLockV3(t *testing.T) {
	f := parseWith(t, "package-lock.json", `{
	  "lockfileVersion": 3,
	  "packages": {
	    "": {"name": "root", "version": "1.0.0"},
	    "node_modules/lodash": {"version": "4.17.21"},
	    "node_modules/@babel/core": {"version": "7.24.0"},
	    "node_modules/a/node_modules/lodash": {"version": "3.10.1"},
	    "node_modules/linked": {"link": true, "version": "1.0.0"}
	  }
	}`)
	wantPkg(t, f, "lodash", "3.10.1", "4.17.21")
	wantPkg(t, f, "@babel/core", "7.24.0")
	if _, ok := f.Packages["linked"]; ok {
		t.Error("link entries should be skipped")
	}
}


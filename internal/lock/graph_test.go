func TestComposerLockGraph(t *testing.T) {
	f := parseWith(t, "composer.lock", `{
	  "packages": [
	    {"name": "monolog/monolog", "version": "3.6.0",
	     "require": {"php": ">=8.1", "psr/log": "^2.0 || ^3.0"}}
	  ],
	  "packages-dev": [
	    {"name": "psr/log", "version": "3.0.0", "require": {"php": ">=8.0.0"}}
	  ]
	}`)
	wantEdge(t, f, "monolog/monolog", "psr/log")
	if len(f.Deps["monolog/monolog"]) != 1 {
		t.Errorf("platform requires (php) must be skipped, got %v", f.Deps["monolog/monolog"])
	}
}


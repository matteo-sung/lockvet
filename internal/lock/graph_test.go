func TestPoetryLockGraph(t *testing.T) {
	f := parseWith(t, "poetry.lock", `[[package]]
name = "requests"
version = "2.32.3"
description = "HTTP for Humans"

[package.dependencies]
urllib3 = ">=1.21.1,<3"
certifi = ">=2017.4.17"

[package.extras]
socks = ["PySocks (>=1.5.6)"]

[[package]]
name = "urllib3"
version = "2.2.1"
description = ""

[[package]]
name = "certifi"
version = "2024.2.2"
description = ""

[metadata]
lock-version = "2.0"
`)
	wantEdge(t, f, "requests", "urllib3")
	wantEdge(t, f, "requests", "certifi")
	if f.RootsKnown {
		t.Error("poetry.lock records no root info")
	}
	if _, ok := f.Deps["requests"]; !ok {
		t.Fatal("expected deps for requests")
	}
	for _, d := range f.Deps["requests"] {
		if d == "socks" || d == "PySocks" {
			t.Error("extras must not become edges")
		}
	}
}


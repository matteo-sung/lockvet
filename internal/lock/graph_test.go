package lock

import (
	"reflect"
	"sort"
	"testing"
)

func wantRoots(t *testing.T, f *File, roots ...string) {
	t.Helper()
	if !f.RootsKnown {
		t.Fatalf("%s: RootsKnown = false, want true", f.Kind)
	}
	got := append([]string(nil), f.Roots...)
	sort.Strings(got)
	sort.Strings(roots)
	if !reflect.DeepEqual(got, roots) {
		t.Errorf("%s: roots = %v, want %v", f.Kind, got, roots)
	}
}

func wantEdge(t *testing.T, f *File, from, to string) {
	t.Helper()
	for _, d := range f.Deps[from] {
		if d == to {
			return
		}
	}
	t.Errorf("%s: missing edge %s -> %s (deps: %v)", f.Kind, from, to, f.Deps[from])
}

func TestPackageLockV3Graph(t *testing.T) {
	f := parseWith(t, "package-lock.json", `{
	  "lockfileVersion": 3,
	  "packages": {
	    "": {"name": "root", "dependencies": {"express": "^4"}, "devDependencies": {"jest": "^29"}},
	    "node_modules/express": {"version": "4.17.1", "dependencies": {"debug": "2.6.9"}},
	    "node_modules/debug": {"version": "2.6.9", "dependencies": {"ms": "2.0.0"}},
	    "node_modules/ms": {"version": "2.0.0"},
	    "node_modules/jest": {"version": "29.0.0"}
	  }
	}`)
	wantRoots(t, f, "express", "jest")
	wantEdge(t, f, "express", "debug")
	wantEdge(t, f, "debug", "ms")
}

func TestPackageLockWorkspaceGraph(t *testing.T) {
	f := parseWith(t, "package-lock.json", `{
	  "lockfileVersion": 3,
	  "packages": {
	    "": {"name": "root", "dependencies": {}},
	    "packages/app": {"version": "1.0.0", "dependencies": {"lodash": "^4"}},
	    "node_modules/lodash": {"version": "4.17.21"}
	  }
	}`)
	wantRoots(t, f, "lodash")
	if _, ok := f.Packages["packages/app"]; ok {
		t.Error("workspace member path should not be recorded as a package")
	}
}


func TestPoetryPins(t *testing.T) {
	f := mustParse(t, "poetry.lock", `[[package]]
name = "requests"
version = "2.32.0"
description = "HTTP for Humans"
files = [
    {file = "requests-2.32.0-py3-none-any.whl", hash = "sha256:aaaa"},
    {file = "requests-2.32.0.tar.gz", hash = "sha256:bbbb"},
]

[[package]]
name = "internal-lib"
version = "1.0.0"
files = [
    {file = "internal_lib-1.0.0.tar.gz", hash = "sha256:cccc"},
]

[package.source]
type = "legacy"
url = "https://pypi.corp.internal/simple"
reference = "corp"

[metadata]
content-hash = "ffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff"
`)
	wantPin(t, f, "requests", "2.32.0", "sha256:aaaa sha256:bbbb", "pypi.org")
	wantPin(t, f, "internal-lib", "1.0.0", "sha256:cccc", "pypi.corp.internal")
}


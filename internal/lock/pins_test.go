func TestPnpmPins(t *testing.T) {
	f := mustParse(t, "pnpm-lock.yaml", `lockfileVersion: '9.0'

packages:

  left-pad@1.3.0:
    resolution: {integrity: sha512-XI5MPzVNApjAyhQzphX8Bkm}

  private-pkg@2.0.0:
    resolution: {integrity: sha512-abc, tarball: https://npm.corp.internal/private-pkg/-/private-pkg-2.0.0.tgz}
`)
	wantPin(t, f, "left-pad", "1.3.0", "sha512-XI5MPzVNApjAyhQzphX8Bkm", "")
	wantPin(t, f, "private-pkg", "2.0.0", "sha512-abc", "npm.corp.internal")
}


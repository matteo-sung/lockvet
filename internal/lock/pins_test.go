func TestPipfilePins(t *testing.T) {
	f := mustParse(t, "Pipfile.lock", `{
  "_meta": {"sources": [
    {"name": "pypi", "url": "https://pypi.org/simple", "verify_ssl": true},
    {"name": "corp", "url": "https://pypi.corp.internal/simple", "verify_ssl": true}
  ]},
  "default": {
    "requests": {"version": "==2.32.0", "hashes": ["sha256:aaaa", "sha256:bbbb"], "index": "pypi"},
    "internal-lib": {"version": "==1.0.0", "hashes": ["sha256:cccc"], "index": "corp"}
  }
}`)
	wantPin(t, f, "requests", "2.32.0", "sha256:aaaa sha256:bbbb", "pypi.org")
	wantPin(t, f, "internal-lib", "1.0.0", "sha256:cccc", "pypi.corp.internal")
}

func TestRequirementsHashPins(t *testing.T) {
	f := mustParse(t, "requirements.txt", `requests==2.32.0 \
    --hash=sha256:aaaa \
    --hash=sha256:bbbb
idna==3.7 --hash=sha256:cccc
plain==1.0
`)
	wantPin(t, f, "requests", "2.32.0", "sha256:aaaa sha256:bbbb", "")
	wantPin(t, f, "idna", "3.7", "sha256:cccc", "")
	wantPin(t, f, "plain", "1.0", "", "")
}


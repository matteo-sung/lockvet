package lock

import "testing"

func wantPin(t *testing.T, f *File, name, ver, integ, host string) {
	t.Helper()
	pm := f.Pin(name, ver)
	if pm.Integrity != integ || pm.Host != host {
		t.Fatalf("%s@%s pin = %+v, want integrity=%q host=%q", name, ver, pm, integ, host)
	}
}

func TestYarnClassicPins(t *testing.T) {
	f := mustParse(t, "yarn.lock", `# yarn lockfile v1

left-pad@^1.3.0:
  version "1.3.0"
  resolved "https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#5b8a3a7765dfe001261dde915589e782f8c94d1e"
  integrity sha512-XI5MPzVNApjAyhQzphX8BkmKsKUxD4LdyK24iZeQGinBN9yTQT3bFlCBy/aVx2HrNcqQGsdot8ghrjyrvMCoEA==
`)
	wantPin(t, f, "left-pad", "1.3.0",
		"5b8a3a7765dfe001261dde915589e782f8c94d1e sha512-XI5MPzVNApjAyhQzphX8BkmKsKUxD4LdyK24iZeQGinBN9yTQT3bFlCBy/aVx2HrNcqQGsdot8ghrjyrvMCoEA==",
		"registry.yarnpkg.com")
}

